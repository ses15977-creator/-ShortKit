import assert from 'node:assert/strict';
import {freshProject,ending,localScenes,duration,sceneAt,basicCaption} from '../lib/shortkit/model.ts';
const p=freshProject();
assert.equal(ending(p),'가게 이름과 주소를 입력해 주세요');
p.subject='도담식당';p.address='서울시 테스트로 12';
assert.equal(ending(p),'도담식당\n서울시 테스트로 12');
assert.equal(ending({...p,category:'product',cta:'comment'}),'고정댓글에서 확인하세요');
assert.equal(ending({...p,category:'product',cta:'profile'}),'프로필 링크에서 확인하세요');
assert.equal(ending({...p,category:'travel'}),'고정댓글에서 자세한 정보를 확인하세요');
assert.equal(ending({...p,category:'info'}),'궁금한 점은 댓글로 알려주세요');
p.assets=[{id:'short',kind:'video',duration:1.25},{id:'photo',kind:'image',duration:4}];
p.scenes=localScenes(p);
assert.equal(p.scenes[0].duration,1.25);
assert.equal(p.scenes[0].text,'');
assert.equal(p.scenes[2].role,'ending');
assert.equal(p.scenes[2].text,ending(p));
assert.equal(new Set(p.scenes.map(s=>s.id)).size,3);
assert.equal(duration(p),9.25);
assert.equal(sceneAt(p,1.25).index,1);
assert.equal(sceneAt(p,5.25).index,2);
assert.equal(sceneAt(p,5.25).local,0);
assert(basicCaption(p).includes('서울시 테스트로 12'));
console.log('Passed: 4 category endings, short-video bounds, unique scenes, timeline boundaries, caption.');
